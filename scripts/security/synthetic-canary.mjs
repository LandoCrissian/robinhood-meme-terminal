import assert from "node:assert/strict";
import {randomBytes} from "node:crypto";

export function canaryEntropy(value) {
  const counts = new Map();
  for (const character of value) counts.set(character, (counts.get(character) ?? 0) + 1);
  return [...counts.values()].reduce((sum, count) => {const p = count / value.length; return sum - p * Math.log2(p);}, 0);
}

// Nonfunctional detector fixture only. A 96-character lowercase hex alphabet
// avoids URL/base64 punctuation and SHA-256/address-length ambiguity. Explicit
// entropy admission avoids a stochastic below-threshold test. Never publish its
// generated bytes or reuse them as a credential.
export function syntheticCanaryText(random = randomBytes) {
  for (let attempt = 0; attempt < 32; attempt++) {
    const bytes = random(48);
    assert.ok(Buffer.isBuffer(bytes) && bytes.length === 48, "Invalid canary randomness source");
    const value = bytes.toString("hex");
    if (canaryEntropy(value) >= 3.75) return 'api_key = "' + value + '"\n';
  }
  throw new Error("Canary entropy admission failed; never waive the detector control");
}
