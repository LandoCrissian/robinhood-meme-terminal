export type ProductionObservation = {
  chainId: number; blockNumber: bigint; blockHash: Hex; timestamp: bigint;
  deploymentBlockHash: Hex; deploymentCanonical: boolean; publicationBlockHash: Hex; publicationCanonical: boolean;
  runtimes: string[]; bindings: string[]; suspended: boolean; latestVersion: number;
  publishedFactory: Address; publishedRuntimeHash: Hex; engineVersion: number;
  feeWei: bigint; supplyWei: bigint; engineChain: bigint; poolFee: number; tickSpacing: number;
};

export function validateCurveProductionObservation(release: CurveProductionRelease, observation: ProductionObservation, nowSeconds: bigint) {
  if (observation.chainId !== 4663 || observation.blockNumber < BigInt(release.publication.blockNumber) + 20n
      || !hash(observation.blockHash) || observation.timestamp > nowSeconds + 15n || observation.timestamp < nowSeconds - 90n
      || !same(observation.deploymentBlockHash, curveProductionDeployment.blockHash) || !observation.deploymentCanonical
      || !same(observation.publicationBlockHash, release.publication.blockHash) || !observation.publicationCanonical
      || observation.runtimes.length !== Object.keys(curveProductionPins).length
      || observation.runtimes.some((runtime, index) => !same(runtime, Object.values(curveProductionPins)[index][1]))
      || observation.bindings.length !== requiredBindings.length
      || observation.bindings.some((binding, index) => !same(binding, requiredBindings[index][2]))
      || observation.suspended || observation.latestVersion < 1 || observation.engineVersion !== 1
      || !same(observation.publishedFactory, curveProductionPins.factory[0])
      || !same(observation.publishedRuntimeHash, curveProductionPins.factory[1])
      || observation.feeWei !== curveProductionDeployment.creationFeeWei || observation.supplyWei !== launchTokenSupplyWei
      || observation.engineChain !== 4663n || observation.poolFee !== 3000 || observation.tickSpacing !== 60) {
    throw new Error("Production deployment or publication unavailable");
  }
}

async function observe(release: CurveProductionRelease, rpc: Reader, blockNumber: bigint): Promise<ProductionObservation> {
  const read = (contract: keyof typeof curveProductionPins, functionName: (typeof views)[number]["name"]) => rpc.readContract({
    address: curveProductionPins[contract][0], abi: views, functionName, blockNumber,
  });
  const [chainId, block, deployed, deploymentReceipt, publicationBlock, receipt, codes, bindings, suspended, version, approved, fee, supply, engineVersion, engineChain, poolFee, tickSpacing] = await Promise.all([
    rpc.getChainId(), rpc.getBlock({ blockNumber }), rpc.getBlock({ blockNumber: curveProductionDeployment.blockNumber }),
    rpc.getTransactionReceipt({ hash: curveProductionDeployment.transactionHash }),
    rpc.getBlock({ blockNumber: BigInt(release.publication.blockNumber) }), rpc.getTransactionReceipt({ hash: release.publication.transactionHash }),
    Promise.all(Object.values(curveProductionPins).map(([address]) => rpc.getCode({ address, blockNumber }))),
    Promise.all(requiredBindings.map(([contract, fn]) => read(contract, fn))),
    read("directory", "suspended"), read("directory", "latestVersion"),
    rpc.readContract({ address: curveProductionPins.directory[0], abi: views, functionName: "factories", args: [1], blockNumber }),
    read("factory", "creationFeeWei"), read("factory", "tokenSupply"), read("factory", "engineVersion"),
    read("engine", "CHAIN_ID"), read("engine", "POOL_FEE"), read("engine", "TICK_SPACING"),
  ]);
  const events = receipt.logs.length <= 80 ? parseEventLogs({ abi: [publishedEvent], logs: receipt.logs.filter((log) => same(log.address, curveProductionPins.directory[0])), strict: true }) : [];
  const event = events[0];
  return { chainId, blockNumber: block.number, blockHash: block.hash, timestamp: block.timestamp,
    deploymentBlockHash: deployed.hash, deploymentCanonical: deploymentReceipt.status === "success"
      && deploymentReceipt.blockNumber === curveProductionDeployment.blockNumber && same(deploymentReceipt.blockHash, deployed.hash)
      && same(deploymentReceipt.transactionHash, curveProductionDeployment.transactionHash), publicationBlockHash: publicationBlock.hash,
    publicationCanonical: receipt.status === "success" && same(receipt.blockHash, publicationBlock.hash)
      && receipt.blockNumber === BigInt(release.publication.blockNumber) && same(receipt.transactionHash, release.publication.transactionHash)
      && events.length === 1 && event.args.version === 1 && same(event.args.factory, curveProductionPins.factory[0])
      && same(event.args.runtimeHash, curveProductionPins.factory[1]),
    runtimes: codes.map((code) => code && code !== "0x" ? keccak256(code) : "0x"), bindings: bindings.map(String),
    suspended: Boolean(suspended), latestVersion: Number(version), publishedFactory: approved[0], publishedRuntimeHash: approved[1],
    feeWei: BigInt(fee), supplyWei: BigInt(supply), engineVersion: Number(engineVersion), engineChain: BigInt(engineChain),
    poolFee: Number(poolFee), tickSpacing: Number(tickSpacing) };
}

export async function verifyCurveProduction(release: CurveProductionRelease, readers = productionReaders()) {
  if (readers.length !== 2) throw new Error("Two independent providers required");
  const heads = await Promise.all(readers.map((rpc) => rpc.getBlock({ blockTag: "latest" })));
  const blockNumber = heads[0].number < heads[1].number ? heads[0].number : heads[1].number;
  const observations = await Promise.all(readers.map((rpc) => observe(release, rpc, blockNumber)));
  for (const observation of observations) validateCurveProductionObservation(release, observation, BigInt(Math.floor(Date.now() / 1000)));
  if (!same(observations[0].blockHash, observations[1].blockHash)) throw new Error("Production providers disagree");
  return { rpc: readers[0], corroboratingRpc: readers[1], anchor: observations[0] };
}

export function normalizeProductionCreationFields(fields: unknown) {
  if (!keys(fields, ["name", "symbol", "projectURI", "treasury", "treasuryShareBps"])
      || typeof fields.name !== "string" || typeof fields.symbol !== "string" || typeof fields.projectURI !== "string"
      || typeof fields.treasury !== "string" || typeof fields.treasuryShareBps !== "number"
      || !Number.isInteger(fields.treasuryShareBps) || fields.treasuryShareBps < 0 || fields.treasuryShareBps > 9000) return null;
  const result = validateLaunchDraft({ ...emptyLaunchDraft, name: fields.name, symbol: fields.symbol, projectURI: fields.projectURI,
    treasury: fields.treasury, treasuryShare: totalTreasuryFeePercent(fields.treasuryShareBps) }, "total-fee-percent");
  return result.ok && ["name", "symbol", "projectURI", "treasury", "treasuryShareBps"].every((key) =>
    result.draft[key as keyof typeof result.draft] === fields[key]) ? result.draft : null;
}

// Unsigned preparation only. The separate, acceptance-gated wallet controller
// owns explicit user confirmation and recoverable submission. Returning calldata
// never signs or sends a transaction.
export async function prepareCurveProductionCreation(release: CurveProductionRelease, fields: unknown, account: Address, intentId: Hex, prior?: ProductionCreationRequest) {
  const draft = normalizeProductionCreationFields(fields);
  if (!draft || !address(account) || !hash(intentId) || (draft.treasury && [account, curveProductionDeployment.operating,
    curveProductionDeployment.reserve].some((reserved) => same(draft.treasury, reserved)))) throw new Error("Invalid reviewed creation terms");
  const { rpc, anchor } = await verifyCurveProduction(release);
  const creator = getAddress(account.toLowerCase());
  const treasury = draft.treasury ? getAddress(draft.treasury) : zeroAddress;
  const treasuryKind = draft.treasury ? await classifyFixtureTreasury(rpc, treasury, anchor.blockNumber) : "none";
  if (!treasuryKind) throw new Error("Unsupported treasury recipient");
  const deadline = prior ? BigInt(prior.deadline) : anchor.timestamp + 300n;
  if (deadline <= anchor.timestamp || deadline > anchor.timestamp + 300n) throw new Error("Review deadline expired");
  const args = [draft.name, draft.symbol, draft.projectURI, treasury, draft.treasuryShareBps, intentId, deadline] as const;
  const data = encodeFunctionData({ abi: createAbi, functionName: "create", args });
  const transaction = { account: creator, to: curveProductionPins.factory[0], data, value: curveProductionDeployment.creationFeeWei } as const;
  const [confirmedNonce, pendingNonce, gas, canonical, accountCode, delegateCode] = await Promise.all([
    rpc.getTransactionCount({ address: creator, blockTag: "latest" }), rpc.getTransactionCount({ address: creator, blockTag: "pending" }),
    rpc.estimateGas(transaction), rpc.getBlock({ blockNumber: anchor.blockNumber }),
    rpc.getCode({ address: creator, blockNumber: anchor.blockNumber }),
    rpc.getCode({ address: "0x63c0c19a282a1B52b07dD5a65b58948A07DAE32B", blockNumber: anchor.blockNumber }),
    rpc.simulateContract({ address: transaction.to, account: creator, abi: createAbi, functionName: "create", args, value: transaction.value }),
  ]);
  if (confirmedNonce !== pendingNonce || !same(canonical.hash, anchor.blockHash)) throw new Error("Creator nonce or canonical block changed");
  // First-owner activation is distinct from opening creation to every wallet.
  if (!same(creator, "0x7E8E7D3Af28584a8b9eEDDbE16CD3308Bd1e76cA")
      || !accountCode || !same(accountCode, "0xef010063c0c19a282a1b52b07dd5a65b58948a07dae32b")
      || !delegateCode || !same(keccak256(delegateCode), "0xa06befcb6f1d7b6c566a607d9d5d932f9b267f3470e55940225c6ee9c4c5e6b0")) throw new Error("Unsupported creator account or changed delegation");
  if (prior && (prior.nonce !== toHex(confirmedNonce) || !same(prior.data, data))) throw new Error("Original creation identity changed");
  const request: ProductionCreationRequest = { from: creator, to: transaction.to, data, value: toHex(transaction.value), chainId: "0x1237",
    nonce: toHex(confirmedNonce), intentId, deadline: deadline.toString(),
    blockNumber: prior?.blockNumber ?? toHex(anchor.blockNumber), blockHash: prior?.blockHash ?? anchor.blockHash };
  if (prior) {
    const reviewedBlock = await rpc.getBlock({ blockNumber: BigInt(prior.blockNumber) });
    if (!same(reviewedBlock.hash, prior.blockHash)) throw new Error("Original review was invalidated");
  }
  return { status: "prepared", request, gasEstimate: toHex(gas), payouts: { operating: curveProductionDeployment.operating,
      reserve: curveProductionDeployment.reserve, treasuryKind }, metadata: { projectURI: draft.projectURI, description: "device-only", artwork: "device-only" },
    finality: "L2_OBSERVED_L1_NOT_PROVEN_BY_THIS_PREPARATION" } as const;
}
