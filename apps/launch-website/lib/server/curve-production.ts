// These are explicit, server-only release attestations, not evidence generated by
// this module. Operators must supply the separately reviewed underlying records.
// A hash alone does not establish independent security review or L1 finality.
export function parseCurveProductionRelease(raw: string | undefined, expectedSha256: string | undefined): CurveProductionRelease | null {
  if (!raw || raw.length > 8_192 || !sha256(expectedSha256)
      || createHash("sha256").update(raw, "utf8").digest("hex") !== expectedSha256) return null;
  try {
    const data: unknown = JSON.parse(raw);
    if (!keys(data, ["profile", "chainId", "origin", "compilerInputSha256", "factoryRuntimeHash", "ownerCreationApprovalSha256",
      "fullSourceVerificationSha256", "operationalAcceptanceSha256", "l1FinalityPolicyAcceptanceSha256", "indexingRecoveryAcceptanceSha256", "publication"])
      || data.profile !== curveProductionProfile || data.chainId !== 4663 || data.origin !== "https://www.rmtlaunch.fun"
      || data.compilerInputSha256 !== curveProductionDeployment.compilerInputSha256
      || typeof data.factoryRuntimeHash !== "string" || !same(data.factoryRuntimeHash, curveProductionPins.factory[1])
      || ![data.ownerCreationApprovalSha256, data.fullSourceVerificationSha256, data.operationalAcceptanceSha256,
        data.l1FinalityPolicyAcceptanceSha256, data.indexingRecoveryAcceptanceSha256].every(sha256)
      || !keys(data.publication, ["transactionHash", "blockNumber", "blockHash"])
      || !hash(data.publication.transactionHash) || !hash(data.publication.blockHash)
      || typeof data.publication.blockNumber !== "string" || !/^[1-9][0-9]{0,15}$/.test(data.publication.blockNumber)
      || BigInt(data.publication.blockNumber) <= curveProductionDeployment.blockNumber) return null;
    return data as CurveProductionRelease;
  } catch { return null; }
}

export function configuredCurveProductionRelease(headers: Headers, env: Record<string, string | undefined> = process.env, requireOrigin = true) {
  if (env.RMT_CURVE_PRODUCTION_PREPARATION !== curveProductionProfile || env.RMT_CURVE_FIXTURE
      || headers.get("host") !== "www.rmtlaunch.fun" || headers.has("forwarded")
      || (headers.has("x-forwarded-host") && headers.get("x-forwarded-host") !== "www.rmtlaunch.fun")
      || headers.get("x-forwarded-proto") !== "https" || (requireOrigin && headers.get("origin") !== "https://www.rmtlaunch.fun")) return null;
  return parseCurveProductionRelease(env.RMT_CURVE_PRODUCTION_RELEASE, env.RMT_CURVE_PRODUCTION_RELEASE_SHA256);
}

